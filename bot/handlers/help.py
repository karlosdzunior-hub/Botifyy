from aiogram import Router, F
from aiogram.types import CallbackQuery

from keyboards import help_keyboard

router = Router()

FAQ_TEXT = """❓ <b>Помощь — FAQ</b>

<b>Как создать бота?</b>
Нажми 🤖 Создать бота → опиши что нужно → ИИ задаст уточняющие вопросы → подтверди и бот будет создан.

<b>Что такое кредиты?</b>
Внутренняя валюта платформы. Тратятся при создании ботов:
• Простой бот — 150 кредитов
• Средний бот — 300 кредитов
• Сложный бот — 600 кредитов
Диалог и исправление ошибок — бесплатно.

<b>Что такое хостинг?</b>
Запуск твоего бота на нашем сервере 24/7. Оплачивается отдельно от кредитов (раз в месяц). Без хостинга ты можешь скачать код и запустить сам.

<b>Как получить кредиты?</b>
• 🎁 150 приветственных при регистрации
• 👥 50 за каждого приглашённого друга
• 💳 Купить в разделе Кредиты

<b>Как пригласить друга?</b>
Раздел 👥 Рефералы → скопируй ссылку → отправь другу.

<b>Мой бот не работает?</b>
Напиши в поддержку — поможем разобраться.

<b>Какие боты можно создать?</b>
Любые: магазины, запись к мастеру, игры, опросы, рассылки, чат-боты, интеграции с API, оплата и многое другое."""


@router.callback_query(F.data == "help")
async def show_help(callback: CallbackQuery):
    await callback.message.edit_text(FAQ_TEXT, reply_markup=help_keyboard(), parse_mode="HTML")
    await callback.answer()
